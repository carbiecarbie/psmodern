    root=Path(folder);rom=root/'synthetic.sms';rom.write_bytes(bytes(512*1024))
    rec=root/'test.psrec';header='psmodern-recording 1\nrom '+hashlib.sha1(rom.read_bytes()).hexdigest()+'\ncart-ram '+hashlib.sha1(bytes([1])*8192).hexdigest()+'\n'
    rec.write_text(header+'end 2\n',encoding='ascii',newline='\n')
    check(load_recording(rec)[2]==2, 'Explicit test check failed')
    args=[str(runner),str(rom),str(rec),'--dump','all','--out',str(root/'out')]
    def rejects(arguments,diagnostic):
        result=subprocess.run(arguments,capture_output=True,text=True)
        check(result.returncode and diagnostic in result.stderr, (result.returncode,result.stderr))
    rejects([str(runner)],'Usage:')
    for selection in ('0','3','2-1','1,','x','1--2'):
        bad=args.copy();bad[4]=selection;rejects(bad,'dump')
    rejects(args,'cartridge RAM SHA-1 mismatch')
    cart=root/'cart';cart.write_bytes(b'x');rejects(args+['--cart-ram',str(cart)],'8192')
    rec.write_text(header.replace(hashlib.sha1(bytes([1])*8192).hexdigest(),hashlib.sha1(bytes(8192)).hexdigest())+'end 2\n',encoding='ascii',newline='\n')
    (root/'out').mkdir();rejects(args,'already exists')
    a=root/'a';b=root/'b';a.mkdir();b.mkdir()
    row='1 '+' '.join(['0'*40]*5)+'\n'
    for p in (a,b):(p/'manifest.txt').write_text(HEADER+'\n'+row,encoding='ascii')
    check(compare(a/'manifest.txt',b/'manifest.txt')==[], 'Explicit test check failed')
    (b/'manifest.txt').write_text(HEADER+'\n'+row.replace('0'*40,'1'*40,1),encoding='ascii')
    (a/'frame-000001.picture.bin').write_bytes(bytes(49152));(b/'frame-000001.picture.bin').write_bytes(bytes(17)+b'x'+bytes(49134))
    result=compare(a/'manifest.txt',b/'manifest.txt');check('frame 1: picture' in result[0] and any('0x0011' in line for line in result), 'Explicit test check failed')
    # A later RAM divergence must be reported even after the first picture difference.
    (a/'manifest.txt').write_text(HEADER+'\n'+row+row.replace('1 ','2 ',1),encoding='ascii')
    second='2 '+'0'*40+' '+'1'*40+' '+' '.join(['0'*40]*3)+'\n'
    (b/'manifest.txt').write_text(HEADER+'\n'+row.replace('0'*40,'1'*40,1)+second,encoding='ascii')
    (a/'frame-000002.ram.bin').write_bytes(bytes(8192));(b/'frame-000002.ram.bin').write_bytes(bytes(5)+b'x'+bytes(8186))
    result=compare(a/'manifest.txt',b/'manifest.txt',[(0xc000,0xc003)])
    check(any('ram: first differing frame 2' in line for line in result) and any('$C005' in line for line in result), 'Explicit test check failed')

    # Exact equality is required for every component, including VRAM.
    rec.write_text(header.replace(hashlib.sha1(bytes([1])*8192).hexdigest(),
                                  hashlib.sha1(bytes(8192)).hexdigest())+'end 2\n',encoding='ascii',newline='\n')
    out=root/'strict'
    subprocess.run([runner,rom,rec,'--dump','1','--out',out],check=True)
    runner_rows=(out/'manifest.txt').read_text().splitlines()
    # Independent authored expectation: the all-NOP fixture never changes
    # memory. This fixture is not a manifest generated by our own runner.
    cram=bytes.fromhex('00 3f 3e 3f 30 30 38 3f 37 3f 00 00 00 00 00 00 00 03 30 0f 07 16 3f 02 00 0f 00 00 00 00 00 00')
    def expected_rows(cart):
        hashes=[hashlib.sha1(data).hexdigest() for data in
                (bytes(49152),b'\xab'+bytes(8191),bytes(16384),cram,cart)]
        identity={'label':'Authored data-free fixture','executable_sha256':'1'*64,
                  'recording_sha256':hashlib.sha256(rec.read_bytes()).hexdigest()}
        return [HEADER]+provenance(identity).splitlines()+[str(n)+' '+' '.join(hashes) for n in (1,2)]
    rows=expected_rows(bytes(8192))
    expected=root/'expected.txt'
    def checkpoint(lines,code):
        expected.write_text('\n'.join(lines)+'\n',encoding='ascii')
        result=subprocess.run([sys.argv[2],rom,rec,expected],capture_output=True,text=True)
        check(result.returncode==code, (result.stdout,result.stderr))
    checkpoint(runner_rows,1)
    checkpoint(rows,0)
    for missing in range(1,5):checkpoint(rows[:missing]+rows[missing+1:],1)
    wrong=rows.copy();wrong[1]='reference psmodern 1';checkpoint(wrong,1)
    wrong=rows.copy();wrong[4]='recording-sha256 '+'f'*64;checkpoint(wrong,1)
    wrong=rows.copy();wrong[2]='build-sha256 invalid';checkpoint(wrong,1)
    wrong=rows.copy();wrong[3]='build-label ""';checkpoint(wrong,1)
    for component in range(1,6):
        changed=rows.copy(); fields=changed[5].split(); fields[component]='f'*40
        changed[5]=' '.join(fields); checkpoint(changed,1)
    checkpoint(rows[:-1],1)
    checkpoint(rows+[rows[-1]],1)

    # A nonzero initial image is loaded beside the checkpoint manifest.
    cart.write_bytes(bytes([1])*8192)
    rec.write_text(header+'end 2\n',encoding='ascii',newline='\n')
    saved=root/'saved'
    subprocess.run([runner,rom,rec,'--dump','all','--out',saved,'--cart-ram',cart],check=True)
    manifest=saved/'manifest.txt'
    manifest.write_text('\n'.join(expected_rows(cart.read_bytes()))+'\n',encoding='ascii')
    def saved_checkpoint(code,diagnostic=''):
        result=subprocess.run([sys.argv[2],rom,rec,manifest],capture_output=True,text=True)
        check(result.returncode==code, (result.stdout,result.stderr))
        check(diagnostic in result.stdout+result.stderr, (result.stdout,result.stderr))
    saved_checkpoint(77,'image missing')
    # Missing dependencies must not hide any already-invalid available file.
    valid_rom=rom.read_bytes();rom.write_bytes(bytes([7])*len(valid_rom))
    saved_checkpoint(1,'Incorrect ROM digest');rom.write_bytes(valid_rom)
    valid_manifest=manifest.read_bytes();manifest.write_text('bad header\n',encoding='ascii')
    saved_checkpoint(1,'Invalid manifest header');manifest.write_bytes(valid_manifest)
    invalid=valid_manifest.decode().splitlines();invalid[5]='1 invalid'
    manifest.write_text('\n'.join(invalid)+'\n',encoding='ascii');saved_checkpoint(1,'Invalid reference hash')
    manifest.write_bytes(valid_manifest.rsplit(b'\n',2)[0]+b'\n');saved_checkpoint(1,'reference frame')
    manifest.write_bytes(valid_manifest)
    valid_recording=rec.read_bytes();rec.write_text('invalid\n',encoding='ascii')
    saved_checkpoint(1);rec.write_bytes(valid_recording)
    # The empty session format remains valid for recorders, not checkpoints.
    rec.write_bytes(valid_recording.replace(b'end 2\n',b'end 0\n'))
    saved_checkpoint(1,'at least one frame');rec.write_bytes(valid_recording)
    image=saved/'cart-ram.bin';image.write_bytes(cart.read_bytes())
    saved_checkpoint(0)
    image.write_bytes(bytes([2])*8192)
    saved_checkpoint(1,'Incorrect ROM or initial cartridge RAM digest')
    image.write_bytes(bytes(8191));saved_checkpoint(1,'exactly 8192 bytes')
    image.write_bytes(bytes(8193));saved_checkpoint(1,'exactly 8192 bytes')
    image.write_bytes(cart.read_bytes())
    manifest.unlink();saved_checkpoint(77,'manifest missing')
    image.write_bytes(bytes(8191));saved_checkpoint(1,'exactly 8192 bytes')
    image.write_bytes(cart.read_bytes());rec.write_text('invalid\n',encoding='ascii')
    saved_checkpoint(1);rec.write_bytes(valid_recording)

    # The launcher publishes a whole directory, including on Unicode paths.
    # A failed process or incomplete capture leaves no destination or staging.
    rec.write_bytes(valid_recording.replace(hashlib.sha1(cart.read_bytes()).hexdigest().encode(),
                                          hashlib.sha1(bytes(8192)).hexdigest().encode()))
    executable=root/'Mesen.exe';executable.write_bytes(b'authored stand-in')
    destination=root/'saída 漢字'
    command=['reference.py',str(executable),str(rom),str(rec),'--dump','all','--out',str(destination)]
    def invoke(fake):
        with patch.object(sys,'argv',command),patch.object(reference.subprocess,'run',fake):reference.main()
    def fails(*args,**kwargs):raise subprocess.CalledProcessError(1,args[0])
    for fake in (fails,lambda *args,**kwargs: subprocess.CompletedProcess(args[0],0)):
        try:invoke(fake)
        except (subprocess.CalledProcessError,ValueError):pass
        else:raise RuntimeError('Failed reference process was accepted')
        check(not destination.exists() and not list(root.glob('.reference-*')),'Partial reference preparation survived failure')
    def captures(command,**kwargs):
        work=Path(kwargs['cwd']).parent
        check('out="../"' in (work/'config.lua').read_text(),'Lua output path must be relative')
        check('dofile([[../config.lua]])' in (work/'capture.lua').read_text(),'Lua config path must be relative')
        settings=json.loads((work/'home/settings.json').read_text())
        check(settings['Debug']['ScriptWindow']['ScriptTimeout']==1200,'Numeric Lua timeout must be set through configuration')
        for n in (1,2):
            for component,size in zip(reference.COMPONENTS,reference.SIZES):
                (work/f'frame-{n:06d}.{component}.bin').write_bytes(bytes(size))
        (work/'complete.txt').write_text('2')
        return subprocess.CompletedProcess(command,0)
    def callback_error(command,**kwargs):
        result=captures(command,**kwargs)
        (Path(kwargs['cwd']).parent/'capture-error.txt').write_text('authored callback failure')
        return result
    try:invoke(callback_error)
    except ValueError as error:check('authored callback failure' in str(error),'Callback diagnostic was lost')
    else:raise RuntimeError('A swallowed Lua callback error was published')
    check(not destination.exists() and not list(root.glob('.reference-*')),'Failed callback left partial output')
    invoke(captures)
    check(destination.is_dir() and not list(root.glob('.reference-*')),'Reference publication failed')
    check('recording-sha256 '+hashlib.sha256(rec.read_bytes()).hexdigest() in (destination/'manifest.txt').read_text(),
          'Published reference must identify its recording')
