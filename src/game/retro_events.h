#pragma once
#include <array>
#include <algorithm>

namespace psmodern::game {
// Each window start and restoration has its own native dispatch boundary.
// 00:392B ends browsing before a nested dialogue reuses the cursor row.
inline constexpr std::array retro_window_entries{
    0x06b4,0x072a,
    0x2eac,0x2ecd,0x2ed9,0x2f3c,0x302f,0x30a0,0x30b7,0x30c3,0x30d5,0x30e1,0x30ed,0x319e,0x31d4,
    0x3464,0x3478,0x34c9,0x3521,0x352d,0x35b6,0x3632,0x3656,0x3665,0x3682,0x36bb,0x36cc,
    0x36dd,0x36ef,0x36fb,0x3707,0x374d,0x3759,0x376b,0x3777,0x3797,
    0x37a3,0x37c3,0x37cf,0x38c1,0x38cd,0x38d9,0x392b,0x3999,0x39a5,
    0x39b1,0x39dd,0x39e9,0x3a12,0x3a21,0x3a46,0x3a79
};
constexpr bool retro_window_entry(int pc) {
    return std::ranges::binary_search(retro_window_entries,pc);
}
static_assert(std::ranges::is_sorted(retro_window_entries));
}
